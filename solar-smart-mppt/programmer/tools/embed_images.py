# Puts the two MSPM0 images (smart-mppt boards before / after 2026-11-13) into the programmer firmware.
# SMPPT_IMAGES=<dir> may point to a folder with smppt.bin and smppt-j5-pa10.bin instead of ../firmware.
Import("env")
import os, subprocess

proj = env.subst("$PROJECT_DIR")
fw = os.path.normpath(os.path.join(proj, "..", "firmware"))
d = os.environ.get("SMPPT_IMAGES")
images = [
    ("pa10", "smart-mppt, поръчки до 12.11 (J5 на PA10/PA11)",
     os.path.join(d, "smppt-j5-pa10.bin") if d else os.path.join(fw, "build-pa10", "smppt.bin")),
    ("pa0", "smart-mppt, от 13.11 (J5 на PA0/PA1)",
     os.path.join(d, "smppt.bin") if d else os.path.join(fw, "build", "smppt.bin")),
]
for _, _, p in images:
    if not os.path.isfile(p):
        raise SystemExit("embed_images: %s is missing: build the MSPM0 firmware first "
                         "(make && make J5=pa10 in ../firmware)" % p)

try:
    rev = subprocess.check_output(["git", "-C", proj, "rev-parse", "--short", "HEAD"]).decode().strip()
except Exception:
    rev = "?"

gen = os.path.join(env.subst("$BUILD_DIR"), "gen")
os.makedirs(gen, exist_ok=True)
out = ["// generated by tools/embed_images.py", "#pragma once", "#include <stdint.h>",
       '#define IMAGES_REV "%s"' % rev]
for i, (key, name, p) in enumerate(images):
    data = open(p, "rb").read()
    rows = [", ".join("0x%02x" % b for b in data[j:j + 24]) for j in range(0, len(data), 24)]
    out.append("static const uint8_t img%d[%d] = {\n  %s\n};" % (i, len(data), ",\n  ".join(rows)))
out.append("struct BuiltIn { const char* key; const char* name; const uint8_t* data; uint32_t len; };")
out.append("static const BuiltIn builtin[] = {")
for i, (key, name, p) in enumerate(images):
    out.append('  { "%s", "%s", img%d, sizeof(img%d) },' % (key, name, i, i))
out.append("};")
open(os.path.join(gen, "images_gen.h"), "w", encoding="utf-8").write("\n".join(out) + "\n")
env.Append(CPPPATH=[gen])
