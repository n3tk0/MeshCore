#!/usr/bin/env python3
"""Builds the 6x12 and 8x14 text fonts of the encoder UI (src/helpers/ui/TextFonts.h).

Input: the BDF files of Terminus Font 4.49.1 by Dimitar Zhekov (SIL Open Font License 1.1),
https://sourceforge.net/projects/terminus-font/ , with the alt/dv1.diff variant applied
(the д and в shapes match the built-in 5x8 Cyrillic font):

  patch -p1 -i alt/dv1.diff
  python3 gen_fonts.py ter-u12b.bdf ter-u14b.bdf > ../../../../src/helpers/ui/TextFonts.h

Only the glyphs the UI can draw are kept: ASCII 0x20..0x7E, then U+0401, U+0410..U+044F, U+0451
(the order of CyrillicFont5x8.h). Rows are stored MSB first, (width + 7) / 8 bytes per row, which
is the layout Adafruit_GFX::drawBitmap() takes.
"""
import sys

CODEPOINTS = list(range(0x20, 0x7F)) + [0x401] + list(range(0x410, 0x450)) + [0x451]


def load(path):
    glyphs, cur, rows, box = {}, None, None, None
    fw = fh = fx = fy = 0
    for line in open(path, encoding="latin-1"):
        t = line.split()
        if not t:
            continue
        if t[0] == "FONTBOUNDINGBOX":
            fw, fh, fx, fy = map(int, t[1:5])
        elif t[0] == "ENCODING":
            cur = int(t[1])
        elif t[0] == "BBX":
            box = list(map(int, t[1:5]))
        elif t[0] == "BITMAP":
            rows = []
        elif t[0] == "ENDCHAR":
            glyphs[cur] = (box, rows)
            rows = None
        elif rows is not None:
            rows.append(int(t[0], 16))
    out = {}
    for cp, (box, rows) in glyphs.items():
        w, h, x, y = box
        nbits = ((w + 7) // 8) * 8
        cell = [0] * fh
        top = (fh + fy) - (h + y)          # rows from the top of the cell
        for r, v in enumerate(rows):
            line = 0
            for c in range(w):
                if v >> (nbits - 1 - c) & 1:
                    line |= 1 << (fw - 1 - (x - fx + c))
            if 0 <= top + r < fh:
                cell[top + r] = line
        out[cp] = cell
    return fw, fh, out


def emit(name, path):
    w, h, glyphs = load(path)
    bpr = (w + 7) // 8
    print(f"// {w}x{h}, {len(CODEPOINTS)} glyphs, from {path.split('/')[-1]}")
    print(f"static const uint8_t {name}_bits[] = {{")
    for cp in CODEPOINTS:
        cell = glyphs.get(cp, [0] * h)
        data = []
        for line in cell:
            v = line << (bpr * 8 - w)
            data += [(v >> (8 * (bpr - 1 - k))) & 0xFF for k in range(bpr)]
        ch = chr(cp) if cp != 0x5C else "backslash"
        print("  " + ", ".join(f"0x{b:02X}" for b in data) + f",  // U+{cp:04X} {ch}")
    print("};")
    print(f"static const TextFont {name} = {{ {w}, {h}, {name}_bits }};")
    print()


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_fonts.py ter-u12b.bdf ter-u14b.bdf")
    print("""#pragma once
// Generated by examples/companion_radio/ui-encoder/tools/gen_fonts.py - do not edit.
//
// Glyphs derived from Terminus Font 4.49.1, Copyright (C) 2020 Dimitar Toshkov Zhekov, licensed
// under the SIL Open Font License 1.1 (see fonts/OFL.txt next to this file). Modified: subset to
// ASCII and Russian/Bulgarian Cyrillic, alt/dv1 variant. This subset is not "Terminus Font".

#include "TextFont.h"
""")
    emit("font_6x12", sys.argv[1])
    emit("font_8x14", sys.argv[2])


main()
