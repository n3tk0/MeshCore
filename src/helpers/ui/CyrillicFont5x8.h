// returns glyph index for a Unicode code point, or -1 if not covered
static inline int cyrillicGlyphIndex(uint16_t cp) {
  if (cp >= 0x0410 && cp <= 0x044F) return CYR_GLYPH_A + (cp - 0x0410);
  if (cp == 0x0401) return CYR_GLYPH_YO;
  if (cp == 0x0451) return CYR_GLYPH_YO_SMALL;
  return -1;
}
